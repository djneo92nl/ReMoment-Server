<?php

namespace App\Domain\Scenes;

use Illuminate\Support\Str;
use Symfony\Component\Yaml\Yaml;

/**
 * The Home Assistant `rest_command` package generated from the scene-capable operations
 * (config/scene-operations.php) and docs/api/openapi.yaml. One command per operation, named
 * `remoment_{snake_case operationId}`; the service data takes the operation's inputs by name (path parameters, query
 * parameters, body properties; the device is the `device_param` input like any other).
 *
 * UNVERIFIED in a running Home Assistant: the shape follows HA's documented rest_command options (`url`, `method`,
 * `payload`, `content_type`, templates over the service data). See docs/architecture/home-assistant.md.
 */
class HaPackage
{
    public function __construct(private readonly SceneOperations $operations) {}

    /** The YAML document as text; `$baseUrl` is the server's origin (no `/api`). */
    public function yaml(string $baseUrl): string
    {
        $header = <<<'TXT'
# ReMoment Server: Home Assistant rest_command package (generated by `php artisan ha:package`).
# Add it as a package (homeassistant: packages: remoment: !include remoment.yaml) or merge it into configuration.yaml.
# Call a command with its inputs as service data, e.g.
#   service: rest_command.remoment_move_playback
#   data: { device: 3, to_device_id: 5 }
# Generated from docs/api/openapi.yaml; it is NOT verified in a running Home Assistant.

TXT;

        return $header.Yaml::dump(['rest_command' => $this->commands($baseUrl)], 6, 2);
    }

    /** @return array<string, array<string, string>> command name => rest_command options */
    public function commands(string $baseUrl): array
    {
        $api = rtrim($baseUrl, '/').'/api';
        $commands = [];

        foreach ($this->operations->all() as $id => $operation) {
            $command = [
                'url' => $api.$this->urlTemplate($operation),
                'method' => $operation['method'],
            ];

            $body = array_filter($operation['inputs'], fn ($input) => $input['in'] === 'body');
            if ($body !== []) {
                $command['content_type'] = 'application/json';
                $command['payload'] = $this->payloadTemplate($body);
            }

            $commands['remoment_'.Str::snake($id)] = $command;
        }

        return $commands;
    }

    /** The path with `{name}` as `{{ name }}`, then the required query parameters (optional ones are left out). */
    private function urlTemplate(array $operation): string
    {
        $path = preg_replace('/\{([^}]+)\}/', '{{ $1 }}', $operation['path']);

        $query = [];
        foreach ($operation['inputs'] as $name => $input) {
            if ($input['in'] === 'query' && $input['required']) {
                $query[] = $name.'={{ '.$name.' | urlencode }}';
            }
        }

        return $path.($query === [] ? '' : '?'.implode('&', $query));
    }

    /**
     * A Jinja template that renders the JSON body: required properties always, optional ones only when the service
     * data has them. Required first, in the schema's order.
     */
    private function payloadTemplate(array $body): string
    {
        uasort($body, fn ($a, $b) => $b['required'] <=> $a['required']);

        $required = [];
        $optional = [];
        foreach ($body as $name => $input) {
            if ($input['required']) {
                $required[] = "'{$name}': {$name}";
            } else {
                $optional[] = "{% if {$name} is defined %}{% set p = dict(p, {$name}={$name}) %}{% endif %}";
            }
        }

        return '{% set p = {'.implode(', ', $required).'} %}'.implode('', $optional).'{{ p | tojson }}';
    }
}
